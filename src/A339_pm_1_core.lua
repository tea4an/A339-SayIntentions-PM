-- The SayIntentions co-pilot acts through her PM ACTIONS checklist items : each one writes an order code into the
-- dataref SpeedyCopilot/si/order. This PM validates the order (speeds, ground only, procedure conditions, read
-- back) and acts, or refuses ; refusals and read backs are said by her (si_bridge.ps1, SAPI sayAs).
