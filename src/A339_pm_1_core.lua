function PM_say(text)
	if text == nil or text == "" then return end
	local f = io.open(PM_DIR .. "si_say_queue.txt", "a")
	if f ~= nil then f:write(text .. "\n") f:close() end
end

function PM_refuse(label, reason)
	PM_log(label .. " : unable. " .. (reason or ""))
	PM_say("Unable. " .. (reason or ""))
end

--########################################
--# READ BACKS                           #
--########################################
-- The PM asks ("Confirm engine start?") and acts only on "confirm" (SpeedyCopilot/confirm, from the bridge)
-- within 45 s : her voice comes several seconds after the question, and the pilot answered after 28 s in flight.
PM_pending_confirm = nil

function PM_ask_confirm(question, label, action)
	PM_pending_confirm = { action = action, label = label, expires = PM_time + 45 }
	PM_log(label .. " : waiting for confirm")
	PM_say(question)
end

function PM_confirm()
	local pending = PM_pending_confirm
	if pending == nil then return end
	PM_pending_confirm = nil
	if PM_time > pending.expires then PM_log(pending.label .. " : too late, not done.") PM_say("Too late. " .. pending.label .. " not done.") return end
	pending.action()
end

function PM_confirm_timeout()
	if PM_pending_confirm ~= nil and PM_time > PM_pending_confirm.expires then
		PM_log(PM_pending_confirm.label .. " : not confirmed, not done.")
		PM_say("Not confirmed. " .. PM_pending_confirm.label .. " not done.")
		PM_pending_confirm = nil
	end
end
do_often("PM_confirm_timeout()")

create_command("SpeedyCopilot/confirm", "A339 PM : CONFIRM the order read back", "PM_confirm()", "", "")

