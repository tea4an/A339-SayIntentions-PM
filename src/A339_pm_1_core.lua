--########################################
--# FCU, QNH, SQUAWK VALUES (bridge)     #
--########################################
-- Her checklist items carry a fixed value only : the numbers come from the bridge, which reads them in the
-- pilot's words to her ("heading one seven five") or, when she handles the radio (siai/copilot = 1), in the ATC
-- instructions. ToLiSs takes the standard X-Plane autopilot datarefs (tested on ground 31.10.2026).
-- In flight : heading and speed are pulled (selected), the altitude is pushed (managed), as the pilot asked.
-- the knob after the value : the pilot's "push" / "pull" when he said it (done even on ground), otherwise the
-- default in flight only (heading and speed pulled, altitude pushed)
local function knob(name, default, mode)
	local which = mode or (PM_airborne() and default) or nil
	if which == "PUSH" then PM_later(0.5, function() command_once("AirbusFBW/Push" .. name) end)
	elseif which == "PULL" then PM_later(0.5, function() command_once("AirbusFBW/Pull" .. name) end) end
	return which and (" " .. which) or ""
end

PM_VALUE = {
	HDG = function(v, from, mode)
		if v < 0 or v > 360 then return false, "Heading " .. v .. " is not valid." end
		if v == 0 then v = 360 end
		set("sim/cockpit2/autopilot/heading_dial_deg_mag_pilot", v)
		return true, "HEADING " .. v .. knob("HDGSel", "PULL", mode)
	end,
	ALT = function(v, from, mode)
		v = math.floor(v / 100 + 0.5) * 100
		if v < 100 or v > 43000 then return false, "Altitude " .. v .. " is not valid." end
		set("sim/cockpit2/autopilot/altitude_dial_ft", v)
		return true, "ALTITUDE " .. v .. knob("Altitude", "PUSH", mode)
	end,
	SPD = function(v, from, mode)
		if v < 100 or v > 350 then return false, "Speed " .. v .. " is not valid." end
		if PM_ref("sim/cockpit2/autopilot/airspeed_is_mach") == 1 then command_once("toliss_airbus/ias_mach_button_push") end
		PM_later(0.3, function() set("sim/cockpit2/autopilot/airspeed_dial_kts_mach", v) end)
		return true, "SPEED " .. v .. knob("SPDSel", "PULL", mode)
	end,
	MACH = function(v, from, mode)
		if v < 0.5 or v > 0.86 then return false, "Mach " .. v .. " is not valid." end
		if PM_ref("sim/cockpit2/autopilot/airspeed_is_mach") == 0 then command_once("toliss_airbus/ias_mach_button_push") end
		PM_later(0.3, function() set("sim/cockpit2/autopilot/airspeed_dial_kts_mach", v) end)
		return true, "MACH " .. v .. knob("SPDSel", "PULL", mode)
	end,
	SPDMANAGED = function()
		command_once("AirbusFBW/PushSPDSel")
		return true, "SPEED MANAGED"
	end,
	QNH = function(v, from) -- hPa, or inHg when below 40 ; from ATC the barometers stay on STD if they are
		local inhg = v
		if v > 40 then inhg = v / 33.8639 end
		if inhg < 27 or inhg > 32 then return false, "QNH " .. v .. " is not valid." end
		if from == "pilot" then PM_baro_std(false) end
		PM_later(0.3, function()
			set("sim/cockpit2/gauges/actuators/barometer_setting_in_hg_pilot", inhg)
			set("sim/cockpit2/gauges/actuators/barometer_setting_in_hg_copilot", inhg)
		end)
		return true, "QNH " .. v
	end,
	SQUAWK = function(v)
		local code = string.format("%04d", v)
		if not string.match(code, "^[0-7][0-7][0-7][0-7]$") then return false, "Squawk " .. code .. " is not valid." end
		-- ToLiSs keeps its own code, one digit per dataref, XPDR4 = first digit ... XPDR1 = last (tested 31.10.2026) ;
		-- the X-Plane dataref alone does not change the ToLiSs transponder
		for i = 1, 4 do set("AirbusFBW/XPDR" .. (5 - i), tonumber(string.sub(code, i, i))) end
		set("sim/cockpit/radios/transponder_code", v)
		return true, "SQUAWK " .. code
	end,
}

-- when the bridge last set each FCU knob : her own PUSH / PULL item for that knob (she presses "HEADING KNOB PUSH"
-- on "set heading 175") would undo what the bridge just did
PM_value_time = {}
local KNOB_OF = { HDG = "fcu_hdg", ALT = "fcu_alt", SPD = "fcu_spd", MACH = "fcu_spd", SPDMANAGED = "fcu_spd" }

function PM_knob_recently_set(id)
	for what, knob in pairs(KNOB_OF) do
		if knob == id and PM_value_time[what] ~= nil and PM_time - PM_value_time[what] < 12 then return true end
	end
	return false
end

-- from = "pilot" (his words to her) or "atc" (only when she handles the radio) ; mode = "PUSH" / "PULL" when said
function PM_value(what, value, from, mode)
	local action = PM_VALUE[what]
	if action == nil then return end
	PM_value_time[what] = PM_time
	if from == "atc" and PM_ref("siai/copilot") ~= 1 then PM_log("ATC " .. what .. " " .. value .. " : the pilot handles the radio, not set") return end
	local ok, text = action(tonumber(value) or 0, from, mode)
	if ok then PM_log(text .. " (" .. from .. ")") else PM_refuse(what, text) end
end

--########################################
--# HER ORDERS (SpeedyCopilot/si/order)  #
--########################################
-- The codes are in docs/si_items.json (switches) and A339_pm_3_procedures.lua (procedures).
-- The same order twice within 3 s is done once.
PM_si_order = create_dataref_table("SpeedyCopilot/si/order", "Float")
PM_si_order[0] = 0
local last_code, last_code_time = nil, -100

-- The bridge acts : it finds every item in the pilot's words (SI|ORDER|n), the procedures and the numbers. Her own
-- press of an item is a fallback only : it waits 3 s and is dropped when the bridge acted on the pilot's words in
-- the 10 s before it (she pressed wrong items - FLAPS TWO on "flaps one" - and after a SayIntentions update none at
-- all, 02.11.2026). Her items stay so that she knows what she can do and answers right.
local bridge_acted = -100
function PM_bridge_mark() bridge_acted = PM_time end -- the bridge, or a procedure (go around : the flaps)

function PM_si_order_watch()
	local code = math.floor((PM_si_order[0] or 0) + 0.5)
	if code == 0 then return end
	PM_si_order[0] = 0
	local action = PM_CODES[code]
	if action == nil then PM_refuse("order " .. code, "I do not know that action.") return end
	if code == last_code and PM_time - last_code_time < 3 then return end
	last_code, last_code_time = code, PM_time
	PM_log("order " .. code .. " from the SayIntentions co-pilot")
	PM_later(3, function()
		if PM_time - bridge_acted < 13 then PM_log("order " .. code .. " skipped : the bridge acted") else PM_log("order " .. code .. " : hers (the bridge did not act)") action() end
	end)
end
do_every_frame("PM_si_order_watch()")

--########################################
--# THE BRIDGE                           #
--########################################
-- si_bridge.ps1 sends over UDP on 127.0.0.1 : "SI|SpeedyCopilot/confirm" (the pilot's answer to a read back) and
-- "SI|PILOT|<HDG|ALT|SPD|MACH|SPDMANAGED|QNH|SQUAWK>|<value>" or "SI|ATC|..." (FCU, QNH, squawk values).
local socket = require("socket")
local udp = nil
for port = PM_port, PM_port + 9 do -- a socket of a previous Lua session can still hold the port
	local u = socket.udp()
	if u:setsockname("127.0.0.1", port) then
		u:settimeout(0)
		udp, PM_port = u, port
		break
	end
	u:close()
end
if udp == nil then PM_log("no free UDP port for the bridge") end

function PM_udp_close()
	if udp ~= nil then udp:close() udp = nil end
end
do_on_exit("PM_udp_close()")

function PM_udp_receive()
	if udp == nil then return end
	for _ = 1, 5 do
		local data = udp:receive()
		if data == nil then return end
		local command = string.match(data, "^SI|(SpeedyCopilot/[%w_/]+)%s*$")
		-- SI|ORDER|1940 : an item the bridge found in the pilot's words (any order code)
		local order = tonumber(string.match(data, "^SI|ORDER|(%d+)%s*$") or "")
		-- SI|PILOT|HDG|175, SI|ATC|ALT|5000, SI|PILOT|ALT|22000|PUSH
		local from, what, value, mode = string.match(data, "^SI|(%a+)|(%u+)|([%d%.]+)|?(%u*)%s*$")
		if command ~= nil or order ~= nil or from == "PILOT" then bridge_acted = PM_time end -- not for ATC
		if command ~= nil then
			PM_log(command .. " from the bridge")
			command_once(command)
		elseif order ~= nil then
			PM_log("order " .. order .. " from the bridge")
			-- "flaps one" said again (a checklist answer) when the flaps are already 1 : nothing to say
			if order >= 10 and order <= 14 then PM_flaps(order - 10, true) else PM_order(order) end
		elseif from ~= nil then
			if mode ~= "PUSH" and mode ~= "PULL" then mode = nil end
			PM_value(what, value, string.lower(from), mode)
		end
	end
end
do_every_frame("PM_udp_receive()")

function PM_bridge_start()
	PM_bridge_stop() -- a bridge still running leaves, the new one takes its place
	os.execute('start "" wscript.exe //nologo "' .. win_path(PM_DIR) .. 'run_hidden.vbs" "' .. win_path(PM_DIR) .. 'si_bridge.ps1" -Port ' .. PM_port)
end

function PM_bridge_stop()
	local f = io.open(PM_DIR .. "si_bridge_quit.flag", "w")
	if f ~= nil then f:write("quit") f:close() end
end

