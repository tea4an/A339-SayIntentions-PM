-- these items only tell her that she can do it (she said "I can't" for the speed and the altitude)
for code = 30, 34 do PM_register_code(code, function() end) end

function PM_order(code)
	if PM_CODES[code] ~= nil then PM_CODES[code]() else PM_log("unknown order code " .. code) end
end

--########################################
--# FLAPS AND GEAR (PF orders)           #
--########################################
local FLAPS_NAMES = { "0", "1", "2", "3", "FULL" }

local function flaps_detent() -- 0 .. 4 (FULL)
	return math.floor(get("sim/flightmodel/controls/flaprqst") * 4 + 0.5)
end

-- VFE of the flaps lever position "target" (1 = CONF 1 ... 4 = FULL) : the A330 placard, or the PFD VFE next when
-- lower (that dataref is 0 when the PFD does not show it).
local function vfe_limit(target)
	local limit = ({ 240, 196, 186, 180 })[target] or 180
	local vfe_next = PM_ref("toliss_airbus/pfdoutputs/general/VFENext_value")
	if vfe_next > 50 and vfe_next < limit then limit = math.floor(vfe_next) end
	return limit
end

function PM_flaps(target, quiet)
	local detent = flaps_detent()
	if target == detent and quiet then PM_log("Flaps already " .. FLAPS_NAMES[detent + 1]) return end
	if target == detent then
		PM_log("Flaps already " .. FLAPS_NAMES[detent + 1])
		PM_say(detent == 0 and "Flaps are already up." or ("Flaps are already " .. FLAPS_NAMES[detent + 1] .. "."))
		return
	end
	-- one step at a time, except retracting on ground (after landing : FULL -> 0 at once)
	local ground_retract = target < detent and not PM_airborne()
	if math.abs(target - detent) > 1 and not ground_retract then PM_refuse("FLAPS", "Flaps are " .. FLAPS_NAMES[detent + 1] .. ". One step at a time.") return end
	local speed = PM_ias()
	if PM_airborne() then
		if target > detent then
			local limit = vfe_limit(target)
			if speed > limit then PM_refuse("FLAPS", "Speed above V F E, " .. limit .. " knots. Flaps " .. FLAPS_NAMES[target + 1] .. " not selected.") return end
		else
			local s_speed = PM_ref("toliss_airbus/pfdoutputs/general/VS_value")
			local f_speed = PM_ref("toliss_airbus/pfdoutputs/general/VF_value")
			if target == 0 and s_speed > 50 and speed < s_speed - 3 then PM_refuse("FLAPS", "Speed below S speed. Flaps zero not selected.") return end
			if target == 1 and f_speed > 50 and speed < f_speed - 3 then PM_refuse("FLAPS", "Speed below F speed. Flaps one not selected.") return end
		end
	end
	set("sim/flightmodel/controls/flaprqst", target / 4)
	PM_log("FLAPS " .. FLAPS_NAMES[target + 1] .. " (IAS " .. math.floor(speed) .. ")")
end

function PM_gear(up)
	if not PM_airborne() then
		if up then PM_refuse("GEAR UP", "We are on the ground.") else PM_log("On ground : the gear is down.") PM_say("The gear is already down.") end
		return
	end
	if PM_ias() > 250 then PM_refuse("GEAR", "Speed above 250 knots.") return end
	if up then
		if PM_vs() <= 0 then PM_refuse("GEAR", "No positive climb.") return end
		command_once("sim/flight_controls/landing_gear_up")
		PM_log("GEAR UP")
	else
		command_once("sim/flight_controls/landing_gear_down")
		PM_log("GEAR DOWN")
	end
end

