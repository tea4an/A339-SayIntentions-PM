PM_CODES = {}   -- order code -> function

function PM_register_code(code, action)
	if PM_CODES[code] ~= nil then PM_log("order code " .. code .. " defined twice") end
	PM_CODES[code] = action
end

-- one switch position, validated
function PM_do(id, index)
	local switch = PM_SWITCHES[id]
	local p = switch.pos[index]
	local label = switch.name .. " " .. p.word
	local in_flight = PM_airborne()
	if not in_flight and PM_gs_kt() > 40 then PM_refuse(label, "Not during the takeoff or landing roll.") return end
	if p.ground and in_flight then PM_refuse(label, "Not in flight.") return end
	if p.check ~= nil then
		local ok, reason = p.check()
		if not ok then if reason ~= nil then PM_refuse(label, reason) end return end -- no reason : the check answered itself
	end
	local question = p.confirm or (in_flight and p.confirm_in_flight)
	local action = function() p.run() PM_log(label) end
	if question then PM_ask_confirm(question, label, action) else action() end
end

-- the same position, no validation (procedures)
function PM_set(id, word)
	local switch = PM_SWITCHES[id]
	for _, p in ipairs(switch.pos) do
		if p.word == word then p.run() PM_log("  " .. switch.name .. " " .. word) return end
	end
	PM_log("unknown position " .. id .. " " .. word)
end

-- order codes only : FlyWithLua allows a limited number of create_command() and crashes X-Plane beyond it
-- (265 switch positions were too many). Test one from the Lua console : PM_order(code).
local FCU_KNOBS = { fcu_hdg = true, fcu_alt = true, fcu_spd = true }

function PM_register_switches()
	for id, switch in pairs(PM_SWITCHES) do
		for i, _ in ipairs(switch.pos) do
			if FCU_KNOBS[id] then
				-- her PUSH / PULL of a knob waits 3 s : skipped when the bridge sets that knob (it may come after her)
				PM_register_code(switch.code + i - 1, function()
					PM_later(3, function()
						if PM_knob_recently_set(id) then PM_log(switch.name .. " " .. switch.pos[i].word .. " skipped : the value was just set")
						else PM_do(id, i) end
					end)
				end)
			else
				PM_register_code(switch.code + i - 1, function() PM_do(id, i) end)
			end
		end
	end
end

