function PM_log(text)
	logMsg("[A339 PM] " .. text)
end

-- dataref value, 0 when the dataref does not exist in this aircraft
function PM_ref(name, index)
	if XPLMFindDataRef(name) == nil then return 0 end
	return get(name, index or 0) or 0
end

function light(index, value)
	set_array("AirbusFBW/OHPLightSwitches", index, value)
end

function PM_agl_m() return get("sim/flightmodel/position/y_agl") end
function PM_airborne() return PM_agl_m() > 5 end
function PM_gs_kt() return get("sim/flightmodel/position/groundspeed") * 1.944 end
function PM_ias() return get("sim/flightmodel/position/indicated_airspeed2") end
function PM_vs() return get("sim/cockpit2/gauges/indicators/vvi_fpm_pilot") end
function PM_altitude() return get("sim/cockpit2/gauges/indicators/altitude_ft_pilot") end
function PM_on_ground(max_kt) return not PM_airborne() and PM_gs_kt() < (max_kt or 50) end
function PM_n1(engine) return get("sim/flightmodel2/engines/N1_percent", engine - 1) end
function PM_both_engines_running() return PM_n1(1) >= 17 and PM_n1(2) >= 17 end

-- actions done a few seconds later : PM_later(seconds, function)
PM_later_queue = {}
function PM_later(seconds, action)
	table.insert(PM_later_queue, { time = PM_time + seconds, action = action })
end
function PM_later_process()
	for i = #PM_later_queue, 1, -1 do
		local item = PM_later_queue[i]
		if PM_time >= item.time then
			table.remove(PM_later_queue, i)
			item.action()
		end
	end
end
do_often("PM_later_process()")

-- buttons that are held (tests)
function PM_hold(command, seconds)
	command_begin(command)
	PM_later(seconds, function() command_end(command) end)
end

function PM_baro_std(std)
	if std then
		if PM_ref("AirbusFBW/BaroStdCapt") ~= 1 then command_once("toliss_airbus/capt_baro_pull") end
		if PM_ref("AirbusFBW/BaroStdFO") ~= 1 then command_once("toliss_airbus/copilot_baro_pull") end
	else
		if PM_ref("AirbusFBW/BaroStdCapt") == 1 then command_once("toliss_airbus/capt_baro_push") end
		if PM_ref("AirbusFBW/BaroStdFO") == 1 then command_once("toliss_airbus/copilot_baro_push") end
	end
end

function PM_check_apu_bleed()
	local packs_on = PM_ref("AirbusFBW/Pack1Switch") == 1 or PM_ref("AirbusFBW/Pack2Switch") == 1
	if PM_airborne() and packs_on and PM_altitude() > 20000 then return false, "APU bleed with packs on is limited to flight level two hundred." end
	-- APU BLEED only once the APU has fully started (APU AVAIL) ; asked during the start, it is set when available
	if PM_ref("AirbusFBW/APUAvail") ~= 1 then
		if PM_ref("AirbusFBW/APUMaster") ~= 1 then return false, "The APU is not running." end
		PM_apu_bleed_waiting = PM_time
		PM_log("APU BLEED ON : waiting for APU AVAIL")
		PM_say("APU bleed on when the APU is available.")
		return false
	end
	return true
end

-- APU start : the starter 5 s after the master switch (both at once is too early)
local apu_master_since = nil
PM_apu_bleed_waiting = nil

function PM_apu_watch()
	if PM_ref("AirbusFBW/APUMaster") == 1 then apu_master_since = apu_master_since or PM_time else apu_master_since = nil end
	if PM_apu_bleed_waiting == nil then return end
	if PM_ref("AirbusFBW/APUAvail") == 1 then
		PM_apu_bleed_waiting = nil
		command_once("toliss_airbus/apucommands/BleedOn")
		PM_log("APU BLEED ON (APU AVAIL)")
	elseif apu_master_since == nil or PM_time - PM_apu_bleed_waiting > 120 then
		PM_apu_bleed_waiting = nil
		PM_log("APU BLEED not set : APU not available")
	end
end
do_often("PM_apu_watch()")

function PM_apu_start()
	local wait = 5
	if apu_master_since ~= nil then wait = math.max(0, apu_master_since + 5 - PM_time)
	else command_once("toliss_airbus/apucommands/MasterOn") end
	PM_later(wait, function()
		if PM_ref("AirbusFBW/APUMaster") == 1 then command_once("toliss_airbus/apucommands/StarterOn") PM_log("  APU STARTER ON") end
	end)
end

